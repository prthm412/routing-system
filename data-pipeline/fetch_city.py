"""
Download the drivable street network inside a bounding box from OpenStreetMap.
Prints how big the network is and saves it to /data/raw/<name>.graphml
(that folder is git-ignored; the data is regenerated by this script).
-------------------------------------------------------------
OpenStreetMap is a trademark of the OpenStreetMap Foundation.
Data (c) OpenStreetMap contributors
-------------------------------------------------------------
"""

import argparse
import time
from pathlib import Path

import osmnx as ox

RAW_DIR = Path("/data/raw")

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--west", type=float, required=True)
    parser.add_argument("--south", type=float, required=True)
    parser.add_argument("--east", type=float, required=True)
    parser.add_argument("--north", type=float, required=True)
    parser.add_argument("--name", required=True, help="output file name, no extension")
    args = parser.parse_args()

    if not (args.south < args.north and args.west < args.east):
        parser.error("need south < north and west < east")

    RAW_DIR.mkdir(parents=True, exist_ok=True)
    ox.settings.cache_folder = str(RAW_DIR / "cache") # re-runs don't redownload

    print(f"osmnx {ox.__version__}")

    start = time.time()
    graph = ox.graph_from_bbox(
        bbox=(args.west, args.south, args.east, args.north),
        network_type="drive",
    )
    print(f"downloaded and built in {time.time() - start:.1f}s")
    print(f"as downloaded: {len(graph.nodes):>7} nodes {len(graph.edges):>7} edges")

    # Keep only the part where you can drive from ANY node to ANY other node
    # Otherwise a delivery could be assigned to a car that can never reach it
    graph = ox.truncate.largest_component(graph, strongly=True)
    print(f"strongly connected: {len(graph.nodes):>7} nodes {len(graph.edges):>7} edges")

    out = RAW_DIR / f"{args.name}.graphml"
    ox.save_graphml(graph, out)
    print(f"saved {out}")

if __name__ == "__main__":
    main()